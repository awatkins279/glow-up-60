/**
 * Production web build → offline-capable PWA.
 *
 *   node scripts/build-web.mjs [--base /glow-up-60]
 *
 * 1. Temporarily sets expo.experiments.baseUrl in app.json (for sub-path hosting like GitHub Pages).
 * 2. Runs `expo export --platform web` into dist/.
 * 3. Injects the PWA manifest, iOS home-screen tags and service-worker registration into index.html.
 * 4. Generates dist/sw.js that precaches every exported file so the app opens with no connection.
 */
import { execSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { copyFileSync, existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const baseIdx = args.indexOf('--base');
const base = baseIdx >= 0 ? (args[baseIdx + 1] ?? '') : '';
// Git Bash (MSYS) rewrites "/glow-up-60" into "C:/.../git/glow-up-60"; keep only the intended segment.
let baseNorm = base.replace(/\\/g, '/').replace(/\/$/, '');
if (/^[A-Za-z]:\//.test(baseNorm)) baseNorm = '/' + baseNorm.split('/').pop();
if (baseNorm && !baseNorm.startsWith('/')) baseNorm = '/' + baseNorm;
// '' or '/glow-up-60'

const appJsonPath = join(root, 'app.json');
const original = readFileSync(appJsonPath, 'utf8');
const appJson = JSON.parse(original);
appJson.expo.experiments = { ...(appJson.expo.experiments ?? {}), baseUrl: baseNorm };
writeFileSync(appJsonPath, JSON.stringify(appJson, null, 2) + '\n');

try {
  console.log(`> expo export --platform web (baseUrl="${baseNorm}")`);
  execSync('npx expo export --platform web --clear', { cwd: root, stdio: 'inherit', env: process.env });
} finally {
  writeFileSync(appJsonPath, original);
}

const dist = join(root, 'dist');

for (const f of ['manifest.json', 'icon-180.png', 'icon-192.png', 'icon-512.png']) {
  const src = join(root, 'public', f);
  if (existsSync(src)) copyFileSync(src, join(dist, f));
}

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, out);
    else out.push(p);
  }
  return out;
}

// ---- index.html: PWA head tags + relative asset URLs
const indexPath = join(dist, 'index.html');
let html = readFileSync(indexPath, 'utf8');
const prefix = baseNorm ? baseNorm + '/' : '/';
html = html.split(`src="${prefix}`).join('src="').split(`href="${prefix}`).join('href="');
html = html.replace(
  '<meta name="viewport" content="width=device-width, initial-scale=1, shrink-to-fit=no" />',
  '<meta name="viewport" content="width=device-width, initial-scale=1, shrink-to-fit=no, viewport-fit=cover, maximum-scale=1, user-scalable=no" />',
);
const head = `
    <meta name="description" content="60-day glow up tracker. Private, offline, on-device." />
    <meta name="theme-color" content="#04060C" />
    <meta name="color-scheme" content="dark" />
    <meta name="mobile-web-app-capable" content="yes" />
    <meta name="apple-mobile-web-app-capable" content="yes" />
    <meta name="apple-mobile-web-app-status-bar-style" content="black-translucent" />
    <meta name="apple-mobile-web-app-title" content="Glow Up 60" />
    <link rel="manifest" href="manifest.json" />
    <link rel="apple-touch-icon" href="icon-180.png" />
    <link rel="icon" type="image/png" href="icon-192.png" />
    <style>
      html, body { background-color: #04060C; color: #EEF3FF; overscroll-behavior-y: none; }
      body { -webkit-tap-highlight-color: transparent; -webkit-touch-callout: none; }
    </style>
    <script>
      if ('serviceWorker' in navigator) {
        window.addEventListener('load', function () {
          navigator.serviceWorker.register('sw.js').catch(function (e) { console.warn('sw register failed', e); });
        });
      }
    </script>
`;
html = html.replace('</head>', head + '</head>');
writeFileSync(indexPath, html);
// GitHub Pages serves 404.html for unknown paths → SPA deep links keep working.
writeFileSync(join(dist, '404.html'), html);

const files = walk(dist)
  .map((p) => relative(dist, p).split(sep).join('/'))
  .filter((p) => p !== 'sw.js' && p !== 'metadata.json');

const version = createHash('sha1')
  .update(files.map((f) => f + statSync(join(dist, f)).size).join('|'))
  .digest('hex')
  .slice(0, 10);

const sw = `/* Glow Up 60 service worker — generated by scripts/build-web.mjs */
const CACHE = 'glowup-${version}';
const BASE = new URL('./', self.location).pathname; // directory the SW lives in
const ASSETS = ${JSON.stringify(files)}.map((f) => BASE + f).concat([BASE]);

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE).then((cache) => cache.addAll(ASSETS)).then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;

  // App navigations (any route) → the cached shell, so deep links work offline.
  if (req.mode === 'navigate') {
    event.respondWith(
      caches.match(BASE + 'index.html').then((cached) => cached || fetch(req).catch(() => caches.match(BASE))),
    );
    return;
  }

  event.respondWith(
    caches.match(req).then((cached) => {
      if (cached) return cached;
      return fetch(req).then((res) => {
        if (res.ok) {
          const copy = res.clone();
          caches.open(CACHE).then((cache) => cache.put(req, copy));
        }
        return res;
      });
    }),
  );
});
`;
writeFileSync(join(dist, 'sw.js'), sw);

const total = files.reduce((n, f) => n + statSync(join(dist, f)).size, 0);
console.log(`\nPWA ready in dist/ — ${files.length} files precached (${(total / 1024 / 1024).toFixed(1)} MB), cache version ${version}`);
